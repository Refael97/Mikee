import { chromium } from "/opt/node22/lib/node_modules/playwright/index.mjs";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
await p.goto("http://localhost:3311/signup");
await p.screenshot({ path: process.argv[2] + "/signup.png", fullPage: true });
const e = `t${Date.now()}@example.com`;
await p.fill("[name=business]", "בדיקה בע״מ");
await p.fill("[name=name]", "דנה כהן");
await p.fill("[name=email]", e);
await p.fill("[name=password]", "a-long-pass-123");
await p.fill("[name=confirm]", "a-long-pass-123");
await p.click("button");
await p.waitForURL(/onboarding/, { timeout: 15000 }).catch(() => {});
console.log("after signup:", p.url());
await p.screenshot({ path: process.argv[2] + "/after.png" });
const m = await b.newPage({ viewport: { width: 390, height: 844 } });
await m.goto("http://localhost:3311/login");
await m.screenshot({ path: process.argv[2] + "/login-m.png", fullPage: true });
await b.close();
